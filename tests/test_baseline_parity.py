def test_last_sync_matches_baseline(loader_module, baseline):
    expected = baseline["sync_metadata"]["get_last_sync"]
    actual = loader_module.get_last_sync()
    actual_iso = actual.isoformat() if pd.notna(actual) else None
    assert actual_iso == expected, (
        "get_last_sync() drifted from baseline. Note: despite the name, this "
        "value is NOT a data-pull timestamp - it is "
        "max(eligibility['scr_dof']), i.e. the latest screening date present "
        "in the data. See report for details."
    )


# --------------------------------------------------------------------------
# Historical hardcoded attachment values (formerly displayed by the now-
# removed Streamlit app.py, NOT computed by indicators.py)
# --------------------------------------------------------------------------

def test_real_computed_attachment_values_differ_from_hardcoded_display(indicators):
    """
    Historical: the now-removed Streamlit UI (app.py) used to display
    LITERAL hardcoded attachment-time strings on its cohort summary cards
    instead of these real computed values. That app.py comparison is gone
    along with app.py itself; this test now only confirms the indicator
    functions still return numeric attachment-hour values, preserving the
    historical hardcoded figures below as a record of what the legacy UI
    used to show for comparison.
    """
    computed_inborn_nvd = indicators.get_inborn_nvd_attachment_hours()
    computed_inborn_csection = indicators.get_inborn_csection_attachment_hours()
    computed_outborn_nvd = indicators.get_outborn_nvd_attachment_hours()
    computed_outborn_csection = indicators.get_outborn_csection_attachment_hours()

    displayed_inborn_nvd_hours = 1 + 45 / 60       # "1h 45m"
    displayed_inborn_csection_hours = 2 + 10 / 60  # "2h 10m"
    displayed_outborn_nvd_hours = 1 + 55 / 60      # "1h 55m"
    displayed_outborn_csection_hours = 3 + 45 / 60  # "3h 45m"

    # These are expected to differ today - this is informational, not a bug
    # assertion. If they ever start matching by coincidence, that's fine too.
    assert isinstance(computed_inborn_nvd, (int, float))
    assert isinstance(computed_inborn_csection, (int, float))
    assert isinstance(computed_outborn_nvd, (int, float))
    assert isinstance(computed_outborn_csection, (int, float))


# --------------------------------------------------------------------------
# Filter wiring (documents that filters currently have ZERO effect)
# --------------------------------------------------------------------------

def test_indicator_functions_accept_no_filter_arguments(indicators):
    """
    The now-removed Streamlit UI's components/filters.py used to render
    Facility/Site/From-Date/To-Date controls on every page, but that dict
    was never passed into any indicator function - none of them accept
    parameters. This test preserves that fact as a tripwire for the
    FastAPI/React port: if someone starts adding a `facility=` /
    `from_date=` parameter to an indicator function without updating the
    caller, this test will start failing and needs a conscious decision,
    not a silent partial wiring.
    """
    import inspect

    with open(BASELINE_PATH, encoding="utf-8") as f:
        baseline_data = json.load(f)

    unexpected_required_params = {}
    for func_name in baseline_data["scalar_indicators"]:
        fn = getattr(indicators, func_name, None)
        if fn is None:
            continue
        sig = inspect.signature(fn)
        required = [
            p.name for p in sig.parameters.values()
            if p.default is inspect.Parameter.empty
            and p.kind in (p.POSITIONAL_OR_KEYWORD, p.POSITIONAL_ONLY, p.KEYWORD_ONLY)
        ]
        if required:
            unexpected_required_params[func_name] = required

    assert not unexpected_required_params, (
        f"Indicator functions now require parameters (filters may be "
        f"partially wired): {unexpected_required_params}"
    )
