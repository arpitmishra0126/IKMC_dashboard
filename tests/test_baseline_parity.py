"""
Baseline/parity tests for the IKMC Dashboard.

These tests re-run the EXISTING, unmodified functions in
services/indicators.py and compare their output to the frozen values in
tests/baseline/baseline_snapshot.json (generated by tests/capture_baseline.py).

Purpose
-------
1. Today: guard against any accidental change to indicators.py while the
   migration work proceeds around it (refactors of loader/config/merger
   should not change a single number here).
2. Later: once FastAPI endpoints exist, a parallel test module can load the
   same baseline_snapshot.json and assert the HTTP responses match it,
   proving CURRENT STREAMLIT IMPLEMENTATION == NEW FASTAPI IMPLEMENTATION.

Nothing in this file alters business logic. A failing test here means the
computed value changed, not that the test is wrong - re-run
tests/capture_baseline.py deliberately (with justification) if the change
was intentional.
"""
import json
import math
from pathlib import Path

import pandas as pd
import pytest

BASELINE_PATH = Path(__file__).resolve().parent / "baseline" / "baseline_snapshot.json"


@pytest.fixture(scope="session")
def baseline():
    assert BASELINE_PATH.exists(), (
        f"{BASELINE_PATH} not found. Run `python tests/capture_baseline.py` "
        "once to generate it before running the parity suite."
    )
    return json.loads(BASELINE_PATH.read_text(encoding="utf-8"))


def _normalize(value):
    """Mirror the normalization capture_baseline.py applies, so a live call
    and the stored snapshot value can be compared like-for-like."""
    import numpy as np

    if isinstance(value, np.integer):
        return int(value)
    if isinstance(value, np.floating):
        return None if np.isnan(value) else float(value)
    if isinstance(value, np.bool_):
        return bool(value)
    return value


def _assert_matches(actual, expected, name):
    actual = _normalize(actual)
    if isinstance(expected, float) or isinstance(actual, float):
        if expected is None or actual is None:
            assert actual == expected, f"{name}: expected {expected!r}, got {actual!r}"
        else:
            assert math.isclose(actual, expected, rel_tol=0, abs_tol=1e-9), (
                f"{name}: expected {expected!r}, got {actual!r}"
            )
    else:
        assert actual == expected, f"{name}: expected {expected!r}, got {actual!r}"


# --------------------------------------------------------------------------
# Scalar indicators (KPI numbers, percentages, hours, counts, status strings)
# --------------------------------------------------------------------------

def test_all_baseline_scalar_functions_are_covered(indicators, baseline):
    """Tripwire: every function named in the baseline snapshot must still
    exist on services.indicators. Catches accidental renames/removals."""
    missing = [
        name for name in baseline["scalar_indicators"]
        if not hasattr(indicators, name)
    ]
    assert not missing, f"Indicator functions removed/renamed: {missing}"


@pytest.mark.parametrize(
    "func_name",
    sorted(json.loads(BASELINE_PATH.read_text(encoding="utf-8"))["scalar_indicators"].keys())
    if BASELINE_PATH.exists() else [],
)
def test_scalar_indicator_matches_baseline(func_name, indicators, baseline):
    expected = baseline["scalar_indicators"][func_name]
    fn = getattr(indicators, func_name)
    actual = fn()
    _assert_matches(actual, expected, func_name)


# --------------------------------------------------------------------------
# DataFrame-returning indicators (validation detail tables)
# --------------------------------------------------------------------------

@pytest.mark.parametrize(
    "func_name",
    sorted(json.loads(BASELINE_PATH.read_text(encoding="utf-8"))["dataframe_indicators"].keys())
    if BASELINE_PATH.exists() else [],
)
def test_dataframe_indicator_matches_baseline(func_name, indicators, baseline):
    import hashlib

    expected = baseline["dataframe_indicators"][func_name]
    fn = getattr(indicators, func_name)
    df = fn()

    assert list(df.shape) == expected["shape"], f"{func_name}: shape changed"
    assert list(df.columns) == expected["columns"], f"{func_name}: columns changed"

    normalized = df.astype(str).sort_index(axis=1)
    payload = normalized.to_csv(index=False).encode("utf-8")
    content_hash = hashlib.sha256(payload).hexdigest()
    assert content_hash == expected["content_hash"], (
        f"{func_name}: row-level content changed (hash mismatch)"
    )


